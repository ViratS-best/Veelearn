"""Hand-authored question bank for Phase 1 sessions.

Every item carries the fields the session engine needs and the design requires:
a tier (1 recall → 4 contest), four options with a per-distractor `why` so wrong
answers get an instant, specific explanation without a model call, a two-step
hint ladder, and short solution steps for the reteach.

`build_session_seed.py` validates all of this (answer key present, exactly one
correct option, a `why` on every distractor, no duplicate stems) before writing
`veelearn-backend/seed/session_seed.json`.
"""


def Q(skill, tier, stem, options, hints, steps, visual=None):
    """options: list of (text, is_correct, why).

    visual: optional board-mode diagram, as the widget engine's declarative spec
    ({"preset": "function_plot", "params": {...}}). Only where a picture earns its
    place — a number line for an inequality, a line for a slope, an area for work.
    """
    return {
        "skill": skill,
        "tier": tier,
        "stem": stem,
        "options": options,
        "hints": hints,
        "steps": steps,
        "visual": visual,
    }


