def convert_mmlu():
    import pyarrow.parquet as pq

    path = fetch("mmlu")
    spec = DATASETS["mmlu"]
    made = 0
    skipped = 0
    per_subject = {}
    for row in rows(path):
        subject = str(row.get("subject") or "")
        skill = mmlu_subject_skill(subject)
        if not skill:
            skipped += 1
            continue
        choices = list(row.get("choices") or [])
        idx = row.get("answer")
        if len(choices) != 4 or not isinstance(idx, int) or not (0 <= idx < 4):
            skipped += 1
            continue
        options = [
            {
                "k": LETTERS[i],
                "t": clean_text(c),
                "why": "" if i == idx else "This option does not answer the question asked.",
            }
            for i, c in enumerate(choices)
        ]
        tier = 2 if subject.startswith(("high_school", "elementary", "conceptual")) else 3
        item = pack(
            skill,
            tier,
            clean_text(row.get("question")),
            options,
            LETTERS[idx],
            generic_hints(subject),
            [
                f"The correct answer is: {clean_text(choices[idx])}.",
                "Check the other choices against the definition in the stem.",
            ],
            spec["source"],
            spec["attribution"],
        )
        if not item:
            skipped += 1
            continue
        per_subject[subject] = per_subject.get(subject, 0) + 1
        made += 1
        yield item
    print(f"  mmlu: {made} items from {len(per_subject)} subjects ({skipped} skipped)")


def convert_openbookqa():
    path = fetch("openbookqa")
    spec = DATASETS["openbookqa"]
    made = 0
    skipped = 0
    for row in rows(path):
        choices = row.get("choices") or {}
        texts = list(choices.get("text") or [])
        labels = list(choices.get("label") or [])
        answer_key = str(row.get("answerKey") or "").strip()
        if len(texts) != 4:
            skipped += 1
            continue
        options = [
            {
                "k": LETTERS[i],
                "t": clean_text(t),
                "why": "" if labels[i] == answer_key else "This choice does not fit what the stem describes.",
            }
            for i, t in enumerate(texts)
        ]
        answer = LETTERS[labels.index(answer_key)] if answer_key in labels else None
        if not answer:
            skipped += 1
            continue
        item = pack(
            "open.elem.science",
            1 if row.get("id", "").startswith("8-") else 2,
            clean_text(row.get("question_stem")),
            options,
            answer,
            ["Think about what the everyday situation is asking for.", "Eliminate choices that are simply untrue."],
            [f"The best answer is: {clean_text(texts[labels.index(answer_key)])}."],
            spec["source"],
            spec["attribution"],
        )
        if not item:
            skipped += 1
            continue
        made += 1
        yield item
    print(f"  openbookqa: {made} items ({skipped} skipped)")


NUM_RE = re.compile(r"####\s*(-?[\d,]+(?:\.\d+)?)")


def _number(text):
    raw = str(text).replace(",", "")
    value = float(raw)
    if abs(value - round(value)) < 1e-9:
        return int(round(value))
    return round(value, 2)


def _distractors(answer, rng):
    """Three believable wrong answers, each with the mistake it stands for."""
    options = []
    candidates = [
        (answer * 2, "That doubles the answer instead of stopping there."),
        (answer / 2, "That halves the answer."),
        (answer + 1, "That is off by one — check the last step."),
        (answer - 1, "That is off by one — check the last step."),
        (answer + 10, "That is ten too many — check the place values."),
        (answer - 10, "That is ten too few — check the place values."),
        (answer * 3, "That repeats one step too often."),
        (answer + answer / 4, "That adds a quarter of the answer."),
    ]
    rng.shuffle(candidates)
    seen = {answer}
    for value, why in candidates:
        if len(options) == 3:
            break
        if isinstance(value, float) and abs(value - round(value)) > 1e-9:
            value = round(value, 2)
        else:
            value = int(round(value))
        if value in seen or value < 0:
            continue
        seen.add(value)
        options.append((value, why))
    return options


def convert_gsm8k():
    path = fetch("gsm8k")
    spec = DATASETS["gsm8k"]
    rng = random.Random(7)
    made = 0
    skipped = 0
    for row in rows(path):
        question = clean_text(row.get("question"))
        answer_text = clean_text(row.get("answer"))
        match = NUM_RE.search(answer_text)
        if not question or not match:
            skipped += 1
            continue
        try:
            value = _number(match.group(1))
        except ValueError:
            skipped += 1
            continue
        if value <= 0:
            skipped += 1
            continue
        wrongs = _distractors(value, rng)
        if len(wrongs) != 3:
            skipped += 1
            continue
        options = [{"k": LETTERS[0], "t": str(value), "why": ""}]
        for i, (w, why) in enumerate(wrongs, start=1):
            options.append({"k": LETTERS[i], "t": str(w), "why": why})
        rng.shuffle(options)
        answer = next(o["k"] for o in options if o["why"] == "")
        # The worked solution travels with the question, stripped of calculator marks.
        steps = [
            re.sub(r"<<[^>]*>>", "", line).strip()
            for line in answer_text.split("\n")
            if line.strip() and not line.strip().startswith("####")
        ]
        item = pack(
            "open.word.problems",
            2 if len(question) < 160 else 3,
            question,
            options,
            answer,
            [
                "Name the quantities you know and the one you need.",
                "Work one step at a time and keep the units.",
            ],
            steps[:5] or [f"The answer is {value}."],
            spec["source"],
            spec["attribution"],
        )
        if not item:
            skipped += 1
            continue
        made += 1
        yield item
    print(f"  gsm8k: {made} items ({skipped} skipped)")


