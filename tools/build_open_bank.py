AUTHORED_ATTRIBUTION = "Veelearn original — generated for Veelearn"


# --------------------------------------------------------------------------- #
# Helpers
# --------------------------------------------------------------------------- #


def fetch(dataset_id: str) -> Path:
    spec = DATASETS[dataset_id]
    CACHE.mkdir(parents=True, exist_ok=True)
    path = CACHE / spec["file"]
    if path.exists() and path.stat().st_size > 1000:
        return path
    print(f"  downloading {dataset_id} …")
    with urllib.request.urlopen(spec["url"], timeout=300) as resp:
        data = resp.read()
    path.write_bytes(data)
    return path


def rows(path: Path):
    import pyarrow.parquet as pq

    table = pq.read_table(path)
    for row in table.to_pylist():
        yield row


def clean_text(value) -> str:
    text = str(value or "")
    text = text.replace("\r\n", "\n").strip()
    return text


def pack(skill, tier, stem, options, answer, hints, steps, source, attribution):
    """Validate and normalise one item; returns None when it cannot be served."""
    # A handful of dataset rows are a single word (OpenBookQA stems that rely on the
    # diagram, MMLU 'which term' rows); they make no sense as a card on their own.
    if not stem or len(stem.strip()) < 8 or not options or len(options) != 4:
        return None
    texts = [str(o["t"]).strip() for o in options]
    if len(set(texts)) != 4 or any(not t for t in texts):
        return None
    keys = [o["k"] for o in options]
    if answer not in keys:
        return None
    key = norm_stem(stem)
    return {
        "skill": skill,
        "tier": tier,
        "stem": stem[:1200],
        "stem_hash": hashlib.sha256(key.encode("utf-8")).hexdigest(),
        "options": [
            {"k": o["k"], "t": str(o["t"])[:600], "why": str(o.get("why", ""))[:400]} for o in options
        ],
        "answer": answer,
        "hints": [h for h in (hints or []) if h][:3],
        "steps": [s for s in (steps or []) if s][:6],
        "visual": None,
        "source": source,
        "attribution": attribution,
    }


def generic_hints(subject=""):
    subject_note = f"This is a {subject.replace('_', ' ')} question." if subject else ""
    return [
        f"{subject_note} Read the stem once more and name exactly what is being asked.".strip(),
        "Eliminate the options that misstate a definition or a fact.",
    ]


