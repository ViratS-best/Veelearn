def build():
    seen = set()
    counts = {}
    total = 0
    items_out = []

    def add(item):
        nonlocal total
        # qbank_items.stem_hash is globally unique, so a stem can only live under
        # one skill. Dataset rows are checked against every generated stem too.
        key = item["stem_hash"]
        if key in seen:
            return
        seen.add(key)
        counts[item["source"]] = counts.get(item["source"], 0) + 1
        total += 1
        items_out.append(item)

    print("importing open datasets …")
    for item in convert_mmlu():
        add(item)
    for item in convert_openbookqa():
        add(item)
    for item in convert_gsm8k():
        add(item)

    print("generating Veelearn practice questions …")
    gen = build_generated()
    for item in gen:
        packed = pack(
            item["skill"],
            item["tier"],
            item["stem"],
            item["options"],
            item["answer"],
            item["hints"],
            item["steps"],
            "authored",
            AUTHORED_ATTRIBUTION,
        )
        if packed:
            add(packed)
    print(f"  generated: {len(gen)} built, {counts.get('authored', 0)} unique")

    # Stable order keeps the committed file diffable.
    items_out.sort(key=lambda it: (it["skill"], it["stem_hash"]))

    OUT_JSONL.parent.mkdir(parents=True, exist_ok=True)
    with gzip.open(OUT_JSONL, "wb", compresslevel=9) as fh:
        for item in items_out:
            fh.write((json.dumps(item, ensure_ascii=False, separators=(",", ":")) + "\n").encode("utf-8"))

    skills = {}
    for item in items_out:
        skills[item["skill"]] = skills.get(item["skill"], 0) + 1

    digest = hashlib.sha256(OUT_JSONL.read_bytes()).hexdigest()
    meta = {
        "version": digest[:16],
        "builtAt": __import__("datetime").datetime.utcnow().isoformat() + "Z",
        "total": len(items_out),
        "bySource": counts,
        "bySkill": skills,
        "skills": len(skills),
        "datasets": [
            {
                "id": key,
                "source": spec["source"],
                "license": spec["license"],
                "attribution": spec["attribution"],
                "url": spec["url"],
            }
            for key, spec in DATASETS.items()
        ],
        "generated": {
            "source": "authored",
            "attribution": AUTHORED_ATTRIBUTION,
            "note": "Computed by tools/gen_bank.py: original Veelearn practice items.",
        },
    }
    OUT_META.write_text(json.dumps(meta, ensure_ascii=False, indent=1), encoding="utf-8")

    size_mb = OUT_JSONL.stat().st_size / (1024 * 1024)
    print(f"\nOK  {OUT_JSONL.relative_to(ROOT)}  {size_mb:.1f} MB compressed")
    print(f"    {len(items_out)} questions across {len(skills)} skills")
    for source, count in sorted(counts.items()):
        print(f"      {source:<12} {count:>6}")
    print(f"    version {meta['version']}")
    return 0


def check():
    if not OUT_JSONL.exists() or not OUT_META.exists():
        print("no build to check — run: python tools/build_open_bank.py")
        return 1
    meta = json.loads(OUT_META.read_text(encoding="utf-8"))
    open_codes = {s["code"] for s in open_skill_rows()}
    problems = []
    seen = set()
    rows = 0
    with gzip.open(OUT_JSONL, "rt", encoding="utf-8") as fh:
        for line in fh:
            rows += 1
            item = json.loads(line)
            if item["skill"] not in open_codes:
                problems.append(f"unknown skill {item['skill']}")
            if item["answer"] not in {o["k"] for o in item["options"]}:
                problems.append(f"bad key: {item['stem'][:40]}")
            if len({o["t"] for o in item["options"]}) != 4:
                problems.append(f"duplicate options: {item['stem'][:40]}")
            key = item["stem_hash"]
            if key in seen:
                problems.append(f"duplicate stem: {item['stem'][:40]}")
            seen.add(key)
            if not item["hints"] or not item["steps"]:
                problems.append(f"missing hints/steps: {item['stem'][:40]}")
            if not item["attribution"]:
                problems.append(f"missing attribution: {item['stem'][:40]}")
            if len(problems) > 20:
                break
    if rows != meta["total"]:
        problems.append(f"row count {rows} != meta {meta['total']}")
    if problems:
        print("CHECK FAILED")
        for p in problems[:20]:
            print("  -", p)
        return 1
    print(f"OK  {rows} questions, {meta['skills']} skills, version {meta['version']}")
    for source, count in sorted(meta["bySource"].items()):
        print(f"      {source:<12} {count:>6}")
    return 0


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    raise SystemExit(check() if args.check else build())
